/// 🆕 مفاتيح تفعيل/تعطيل مركزية لبعض واجهات التطبيق.
///
/// حالياً مقفولة (false) بناءً على طلب الإدارة، لحتى يتحدد موعد تفعيلها
/// لاحقاً. لتفعيل أي واجهة منهن، بس غيّر القيمة لـ true هون — كل
/// أماكن الدخول إلها بالتطبيق (الصفحة الرئيسية، القائمة الجانبية،
/// الشريط السفلي، والإشعارات) عم تعتمد على نفس هالقيمة تلقائياً.
class FeatureFlags {
  FeatureFlags._();

  /// واجهة "النقل" — بلاطة الصفحة الرئيسية + فتحها من إشعار نوعه transportation.
  static const bool showTransportation = false;

  /// واجهة "المالية" — بلاطة الصفحة الرئيسية + عنصر القائمة الجانبية +
  /// فتحها من إشعار نوعه finance.
  static const bool showFinance = false;

  /// واجهة "الدرجات" — بلاطة الصفحة الرئيسية + تبويب الشريط السفلي +
  /// عنصر القائمة الجانبية + فتحها من إشعار نوعه grade/grades.
  static const bool showGrades = false;
}
